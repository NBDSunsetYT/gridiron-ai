import {afterAll,beforeAll,expect,it} from 'vitest';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {randomUUID} from 'node:crypto';
const directory=mkdtempSync(join(tmpdir(),'gridiron-export-test-'));
process.env.DATA_DIR=directory;
let db:typeof import('../lib/db');
beforeAll(async()=>{db=await import('../lib/db');});
afterAll(()=>{db.closeDb();rmSync(directory,{recursive:true,force:true});});
it('encrypted account export retains replay inputs and balanced audit postings while excluding other owners and authentication secrets',async()=>{
 const {newSession,SESSION_COOKIE}=await import('../lib/auth'),{postTransaction}=await import('../lib/ledger'),{decryptBackup}=await import('../lib/backups'),route=await import('../app/api/ledger/backup/route');
 const own=randomUUID(),other=randomUUID(),now=new Date().toISOString();
 for(const id of [own,other])db.getDb().prepare('INSERT INTO users(id,email,password_hash,created_at) VALUES(?,?,?,?)').run(id,id+'@example.test','DO-NOT-EXPORT-PASSWORD-HASH',now);
 postTransaction(own,{type:'deposit',amount:'123.45',sportsbook:'DraftKings'});
 postTransaction(other,{type:'deposit',amount:'987.65',sportsbook:'Hard Rock'});
 for(const id of [own,other])db.getDb().prepare('INSERT INTO simulation_inputs(id,user_id,job_id,data,created_at) VALUES(?,?,?,?,?)').run(randomUUID(),id,randomUUID(),JSON.stringify({model:'SIGNED-REPLAY-'+id}),now);
 const password='Synthetic-export-password-2948';
 const response=await route.POST(new Request('http://localhost/api/ledger/backup',{method:'POST',headers:{'content-type':'application/json',cookie:`${SESSION_COOKIE}=${newSession(own)}`},body:JSON.stringify({password})}));
 expect(response.status).toBe(200);
 const payload=await decryptBackup(await response.json(),password) as Record<string,any>;
 expect(payload.ledger.summary.cashBalanceCents).toBe(12345);
 expect(payload.research.simulation_inputs).toHaveLength(1);
 expect(payload.research.simulation_inputs[0].user_id).toBe(own);
 expect(payload.rawLedger.journal).toHaveLength(1);
 expect(payload.rawLedger.postings).toHaveLength(2);
 expect(payload.rawLedger.postings.reduce((n:number,p:any)=>n+p.amount_cents,0)).toBe(0);
 expect(payload.rawLedger.audit).toHaveLength(1);
 expect(JSON.stringify(payload)).not.toContain(other);
 expect(JSON.stringify(payload)).not.toContain('DO-NOT-EXPORT-PASSWORD-HASH');
 expect(payload.research.sessions).toBeUndefined();
});
